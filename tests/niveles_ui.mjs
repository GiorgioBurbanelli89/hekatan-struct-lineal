// Test de NIVELES en el Modo Revit (vite en :4600). Uso: node tests/niveles_ui.mjs
import puppeteer from "puppeteer";
const b = await puppeteer.launch({ headless: "new", channel: "chrome", args: ["--no-sandbox"] });
const p = await b.newPage(); await p.setViewport({ width: 1500, height: 1000 });
const err = []; p.on("pageerror", (e) => err.push(e.message));
await p.goto("http://localhost:4600/workspace/?t=new-blank", { waitUntil: "networkidle2" });
const w = (ms) => new Promise((r) => setTimeout(r, ms)); await w(5000);
let ok = 0, mal = 0; const check = (n, c, d = "") => { c ? ok++ : mal++; console.log((c ? "  ✓ " : "  ✗ ") + n + (d ? "  " + d : "")); };
const lv = () => p.evaluate(() => (window.__hekatanLevels || []).map((l) => l.z));
const clk = (sel, t) => p.evaluate((sel, t) => { const e = [...document.querySelectorAll(sel)].find((x) => (x.textContent || "").trim().startsWith(t) && x.getBoundingClientRect().width > 0); e?.click(); return !!e; }, sel, t);
console.log("1) niveles de partida"); check("0 y 3", JSON.stringify(await lv()) === "[0,3]", JSON.stringify(await lv()));
console.log("2) panel PLANTAS: + Nivel a una cota escrita (entre otros)");
await p.evaluate(() => { const i = document.querySelector(".rv-add input"); i.value = "1.5"; i.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true })); }); await w(400);
check("queda ordenado [0,1.5,3]", JSON.stringify(await lv()) === "[0,1.5,3]", JSON.stringify(await lv()));
console.log("3) no duplica");
await p.evaluate(() => { const i = document.querySelector(".rv-add input"); i.value = "3"; i.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true })); }); await w(300);
check("sigue [0,1.5,3]", JSON.stringify(await lv()) === "[0,1.5,3]");
console.log("4) × quita un nivel intermedio");
await p.evaluate(() => { const f = [...document.querySelectorAll(".rv-niv")].find((x) => x.dataset.z === "1.5"); f?.querySelector(".rv-x")?.click(); }); await w(300);
check("[0,3]", JSON.stringify(await lv()) === "[0,3]", JSON.stringify(await lv()));
console.log("5) cota provisional EDITABLE en el alzado");
await clk(".rv-niv", "Sur"); await w(1000);
await p.evaluate(() => [...document.querySelectorAll("#hk-revit .rv-b")].find((x) => x.textContent.includes("Nivel"))?.click()); await w(600);
await p.mouse.move(900, 330); await w(500);
const t = await p.evaluate(() => [...document.querySelectorAll(".rv-cota-t")].map((e) => e.style.cursor));
check("la cota provisional acepta texto", t.includes("text"), JSON.stringify(t));
await p.keyboard.press("5"); await w(300); await p.keyboard.type(".5"); await p.keyboard.press("Enter"); await w(600);
check("teclear 5.5 crea el nivel a 3+5.5 = 8.5", JSON.stringify(await lv()) === "[0,3,8.5]", JSON.stringify(await lv()));
console.log(`\n${ok} ok · ${mal} fallan · errores: ${err.length}`); if (err.length) console.log(err);
await b.close(); process.exit(mal || err.length ? 1 : 0);
